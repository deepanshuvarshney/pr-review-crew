"""Decide which changed files are worth sending to a reviewer."""

from __future__ import annotations

import re

from prcrew.models import FileDiff

LOCK_NAMES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "cargo.lock",
    "gemfile.lock",
    "composer.lock",
    "go.sum",
    "pipfile.lock",
    "uv.lock",
}

BINARY_EXTENSIONS = {
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".webp",
    ".pdf",
    ".zip",
    ".gz",
    ".tgz",
    ".tar",
    ".wasm",
    ".ico",
    ".woff",
    ".woff2",
    ".ttf",
    ".eot",
    ".mp4",
    ".mp3",
    ".so",
    ".dll",
    ".class",
    ".jar",
    ".pyc",
    ".exe",
    ".bin",
}

GENERATED_SEGMENTS = {"generated", "node_modules", "vendor", "dist", "build"}

GENERATED_MARKERS = (
    "generated by",
    "auto-generated",
    "autogenerated",
    "do not edit",
    "@generated",
    "code generated",
)


def skip_reason(file: FileDiff, ignore_paths: list[str]) -> str | None:
    if file.is_binary:
        return "binary"
    name = file.path.replace("\\", "/").rsplit("/", 1)[-1]
    lowered = name.lower()
    suffix = _suffix(lowered)
    if suffix in BINARY_EXTENSIONS or lowered.endswith(".min.js") or lowered.endswith(".min.css"):
        return "binary"
    if lowered in LOCK_NAMES or lowered.endswith(".lock"):
        return "lockfile"
    parts = [part.lower() for part in file.path.replace("\\", "/").split("/") if part]
    if any(part in GENERATED_SEGMENTS for part in parts[:-1]):
        return "generated"
    if "_generated." in lowered or ".generated." in lowered or lowered.endswith(".pb.go"):
        return "generated"
    added = "\n".join(text for _, text in file.added_lines()).lower()[:800]
    if any(marker in added for marker in GENERATED_MARKERS):
        return "generated"
    for pattern in ignore_paths:
        if _glob_match(file.path, pattern):
            return "ignored"
    return None


def partition(
    files: list[FileDiff], ignore_paths: list[str]
) -> tuple[list[FileDiff], list[FileDiff]]:
    kept: list[FileDiff] = []
    skipped: list[FileDiff] = []
    for file in files:
        reason = skip_reason(file, ignore_paths)
        if reason is None:
            kept.append(file)
            continue
        skipped.append(file.model_copy(update={"skipped_reason": reason}))
    return kept, skipped


def _suffix(name: str) -> str:
    if "." not in name:
        return ""
    return "." + name.rsplit(".", 1)[-1]


def _glob_match(path: str, pattern: str) -> bool:
    cleaned = path.replace("\\", "/").lstrip("./")
    pat = pattern.replace("\\", "/")
    if pat.startswith("./"):
        pat = pat[2:]
    regex = _glob_to_re(pat)
    basename = cleaned.rsplit("/", 1)[-1]
    return re.fullmatch(regex, cleaned) is not None or re.fullmatch(regex, basename) is not None


def _glob_to_re(pattern: str) -> str:
    index = 0
    parts: list[str] = []
    while index < len(pattern):
        if pattern.startswith("**/", index):
            parts.append("(?:.*/)?")
            index += 3
            continue
        if pattern.startswith("**", index):
            parts.append(".*")
            index += 2
            continue
        char = pattern[index]
        if char == "*":
            parts.append("[^/]*")
        elif char == "?":
            parts.append("[^/]")
        else:
            parts.append(re.escape(char))
        index += 1
    return "".join(parts)
