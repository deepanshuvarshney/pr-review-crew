from __future__ import annotations

from pathlib import Path

import pytest

from prcrew.chunking import chunk_files
from prcrew.config import load_settings
from prcrew.diffparse import parse_unified_diff
from prcrew.errors import ConfigError, DiffParseError
from prcrew.filters import partition, skip_reason
from prcrew.models import FileDiff, FileStatus

RENAME = """diff --git a/old.py b/new.py
similarity index 90%
rename from old.py
rename to new.py
index 1111111..2222222 100644
--- a/old.py
+++ b/new.py
@@ -1 +1 @@
-x = 1
+x = 2
"""

BINARY = """diff --git a/a.png b/a.png
new file mode 100644
index 0000000..1111111
Binary files /dev/null and b/a.png differ
"""

QUOTED = """diff --git "a/my file.py" "b/my file.py"
new file mode 100644
--- /dev/null
+++ "b/my file.py"
@@ -0,0 +1 @@
+value = 1
"""

PLAIN = """--- a/pkg/mod.py
+++ b/pkg/mod.py
@@ -1,3 +1,4 @@
+\"\"\"doc\"\"\"
 class A:
     pass
"""

MULTI = """diff --git a/pkg/mod.py b/pkg/mod.py
index 1111111..2222222 100644
--- a/pkg/mod.py
+++ b/pkg/mod.py
@@ -1,3 +1,4 @@
+\"\"\"doc\"\"\"
 class A:
     pass
 
@@ -10,3 +11,3 @@
 def f():
-    return 1
+    return 2
     return
"""


def test_parse_rename_binary_quoted_and_plain() -> None:
    renamed = parse_unified_diff(RENAME)[0]
    assert renamed.path == "new.py"
    assert renamed.old_path == "old.py"
    assert renamed.status == FileStatus.renamed
    assert renamed.added_lines() == [(1, "x = 2")]

    binary = parse_unified_diff(BINARY)[0]
    assert binary.is_binary
    assert binary.path == "a.png"

    quoted = parse_unified_diff(QUOTED)[0]
    assert quoted.path == "my file.py"
    assert quoted.added_lines() == [(1, "value = 1")]

    plain = parse_unified_diff(PLAIN)[0]
    assert plain.path == "pkg/mod.py"
    assert plain.added_lines()[0][1] == '"""doc"""'


def test_line_mapping_across_hunks() -> None:
    file = parse_unified_diff(MULTI)[0]
    added = dict(file.added_lines())
    assert added[1] == '"""doc"""'
    assert added[12] == "    return 2"
    assert 11 not in added


def test_rejects_non_diff_and_accepts_empty() -> None:
    assert parse_unified_diff("   \n") == []
    with pytest.raises(DiffParseError):
        parse_unified_diff("this is not a diff")


def test_skip_lock_generated_binary_and_globs() -> None:
    binary = parse_unified_diff(BINARY)[0]
    assert skip_reason(binary, []) == "binary"
    lock = FileDiff(path="app/poetry.lock", status=FileStatus.added)
    assert skip_reason(lock, []) == "lockfile"
    generated = FileDiff(path="pkg/generated/client.py", status=FileStatus.modified)
    assert skip_reason(generated, []) == "generated"
    marked = FileDiff(
        path="app/models.py",
        status=FileStatus.modified,
        hunks=[],
    )
    marked = parse_unified_diff(
        "diff --git a/app/models.py b/app/models.py\n"
        "--- a/app/models.py\n+++ b/app/models.py\n"
        "@@ -0,0 +1 @@\n+# auto-generated by tool\n"
    )[0]
    assert skip_reason(marked, []) == "generated"
    kept, skipped = partition(
        [binary, lock, FileDiff(path="app/main.py", status=FileStatus.modified)],
        ["**/main.py"],
    )
    assert kept == []
    assert {item.skipped_reason for item in skipped} >= {"binary", "lockfile", "ignored"}


def test_chunker_repeats_file_header() -> None:
    lines = "\n".join(f"+value_{index} = {index}" for index in range(30))
    diff = (
        "diff --git a/app/big.py b/app/big.py\n"
        "new file mode 100644\n--- /dev/null\n+++ b/app/big.py\n"
        f"@@ -0,0 +1,30 @@\n{lines}\n"
    )
    chunks = chunk_files(parse_unified_diff(diff), max_tokens=40)
    assert len(chunks) > 1
    assert all(chunk.text.startswith("FILE: app/big.py") for chunk in chunks)
    assert any(
        "|+value_0" in chunk.text or "|+value_0" in chunk.text.replace(" ", "") for chunk in chunks
    )


def test_config_precedence(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    path = tmp_path / ".prcrew.yml"
    path.write_text(
        "provider: ollama\nagents:\n  security: false\nseverity_threshold: high\n",
        encoding="utf-8",
    )
    monkeypatch.setenv("PRCREW_PROVIDER", "mock")
    monkeypatch.setenv("PRCREW_DISABLE_AGENTS", "performance")
    settings = load_settings(path, overrides={"max_comments": 3})
    assert settings.provider == "mock"
    assert settings.agents.security is False
    assert settings.agents.performance is False
    assert settings.agents.correctness is True
    assert settings.max_comments == 3
    assert settings.severity_threshold.value == "high"
    monkeypatch.setenv("PRCREW_DISABLE_AGENTS", "nope")
    with pytest.raises(ConfigError):
        load_settings(path)
    path.write_text("- not a mapping\n", encoding="utf-8")
    with pytest.raises(ConfigError):
        load_settings(path)
